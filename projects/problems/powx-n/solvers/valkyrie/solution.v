# 阻塞：f64 浮点语义
# 题内触发点：`micro my_pow(x: f64, n: i64) -> f64 { ... x * x ... }` —— 快速幂需要 f64 乘除、负数倒数与 f64 返回值。
# 期望语义：f64 参数/返回与浮点四则。实际：f64 通道在 intrinsic 清退后未实跑验证（工具链冻结），不开降级绿灯。
# 最小复现（本能力首记）：`micro f(x: f64) -> f64 { return 1.0 / x }`，期望编译并对 2.0 返回 0.5，实际 f64 进出与除法未验证。
# 理想算法：二进制快速幂、负指数取倒数，时间 O(log |n|) 空间 O(1)。
